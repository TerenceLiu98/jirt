.libPaths(c('outputs/r-library',.libPaths()))
library(emIRT);library(jsonlite)
set.seed(2026)
control <- list(maxit=5,thresh=1e-30,threads=1,convtype=2)
write_case <- function(name,kwargs,fit){
 fit$call <- NULL
 write_json(list(kwargs=kwargs,expected=unclass(fit)),paste0('tests/fixtures/',name,'.json'),digits=NA,matrix='rowmajor',auto_unbox=TRUE)
}
y <- matrix(sample(c(-1,0,1),48,replace=TRUE),8,6)
s <- getStarts(8,6,1);p <- makePriors(8,6,1)
rc <- list(votes=y,legis.data=data.frame(row.names=seq_len(8)))
for(method in c('em','variational')) {
 ctl <- control;ctl$asEM <- method=='em'
 fit <- binIRT(rc,.starts=s,.priors=p,.control=ctl)
 write_case(paste0('binary_',method),list(votes=y,starts=s,method=method),fit)
}
y <- matrix(sample(0:3,48,replace=TRUE),8,6)
s <- list(x=matrix(rnorm(8),8),beta=matrix(rnorm(6),6),tau=matrix(.5,6),DD=matrix(1,6))
fit <- ordIRT(y,.starts=s,.priors=p,.control=control)
write_case('ordinal',list(responses=y,starts=s,priors=p),fit)
y <- matrix(sample(0:1,48,replace=TRUE),8,6)
s <- list(alpha=matrix(0,6),beta=matrix(0,8),w=matrix(rnorm(6,sd=.1),6),theta=matrix(rnorm(8,sd=.1),8),gamma=matrix(1))
p <- emIRT:::makePriorsE()
fit <- networkIRT(y,.starts=s,.priors=p,.control=control)
write_case('network',list(edges=y,starts=s,priors=p),fit)
y <- matrix(sample(0:8,30,replace=TRUE),6,5)
s <- list(alpha=matrix(1,5),psi=matrix(0,6),beta=matrix(rnorm(6,sd=.1),6),x=matrix(rnorm(3,sd=.1),3))
p <- setNames(lapply(1:4,function(k)list(mu=0,sigma2=1)),c('alpha','psi','beta','x'))
i <- c(0,1,2,0,1)
fit <- poisIRT(y,i=i,NI=3,.starts=s,.priors=p,.control=control)
write_case('poisson',list(counts=y,starts=s,priors=p,document_subject=i),fit)
y <- matrix(sample(c(-1,0,1),48,replace=TRUE),8,6)
d <- list(rc=y,startlegis=matrix(c(0,0,1,0,0,0,1,0)),endlegis=matrix(c(2,1,2,2,2,1,2,2)),bill.session=matrix(rep(0:2,each=2)),T=3)
s <- list(alpha=matrix(0,6),beta=matrix(rnorm(6),6),x=matrix(rnorm(24),8,3))
p <- list(x.mu0=matrix(0,8),x.sigma0=matrix(1,8),omega2=matrix(.1,8),beta.mu=matrix(0,2),beta.sigma=diag(2)*25)
fit <- dynIRT(d,.starts=s,.priors=p,.control=control)
pp <- p;names(pp) <- c('x_mu0','x_variance0','omega2','beta_mu','beta_covariance')
write_case('dynamic',list(votes=y,starts=s,priors=pp,start_period=d$startlegis,end_period=d$endlegis,item_period=d$bill.session),fit)
d <- list(y=matrix(sample(c(-1,1),48,replace=TRUE)),z=cbind(1,seq(-1,1,length.out=8)),g=matrix(rep(0:3,each=2)),i=matrix(rep(0:7,6)),j=matrix(rep(0:5,each=8)),ND=2,NG=4,NI=8,NJ=6,NL=48)
s <- list(alpha=matrix(0,6),beta=matrix(rnorm(6),6),gamma=matrix(rnorm(8),4,2),eta=matrix(0,8),sigma=matrix(1,4))
p <- list(beta.mu=matrix(0,2),beta.sigma=25*diag(2),gamma.mu=matrix(0,2),gamma.sigma=diag(2),sigma.v=matrix(2),sigma.s=matrix(1))
fit <- hierIRT(d,.starts=s,.priors=p,.control=control)
fit$vars$gamma <- lapply(1:4,function(k)fit$vars$gamma[,,k])
fit$vars$beta2 <- lapply(1:6,function(k)fit$vars$beta2[,,k])
pp <- p;names(pp) <- c('beta_mu','beta_covariance','gamma_mu','gamma_covariance','sigma_v','sigma_s')
write_case('hierarchical',list(votes=d$y,subject=d$i,item=d$j,groups=d$g,covariates=d$z,starts=s,priors=pp),fit)
